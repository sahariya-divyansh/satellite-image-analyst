"""Pydantic schemas for HTTP API requests, responses, and RFC 7807 problem details."""

import re
from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from satellite_analyst.planner.schema import QueryPlan


class ProblemDetail(BaseModel):
    """RFC 7807 Problem Details for HTTP APIs."""

    model_config = ConfigDict(extra="allow")

    type: str = Field(
        default="about:blank", description="URI reference identifying the problem type"
    )
    title: str = Field(..., description="Short, human-readable summary of the problem type")
    status: int = Field(..., description="HTTP status code generated by origin server")
    detail: str = Field(..., description="Human-readable explanation specific to this occurrence")
    instance: str | None = Field(
        default=None, description="URI reference identifying specific occurrence"
    )
    code: str | None = Field(default=None, description="Domain error code string")
    errors: list[Any] | None = Field(default=None, description="Detailed validation errors")


class QueryRequest(BaseModel):
    """Natural-language query submission payload."""

    model_config = ConfigDict(extra="forbid")

    query: str = Field(
        ...,
        min_length=3,
        max_length=500,
        description="Natural-language earth observation query (max 500 characters)",
        examples=["Show all water bodies that expanded near Raipur between 2023 and 2025."],
    )
    llm_provider: Literal["rule_based", "gemini", "openai", "ollama"] | None = Field(
        default=None,
        description="Optional planner provider override",
    )

    @field_validator("query")
    @classmethod
    def sanitize_query(cls, value: str) -> str:
        """Strip control characters while preserving printable characters and standard whitespace."""
        cleaned = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", value).strip()
        if len(cleaned) < 3:
            raise ValueError("Query contains insufficient printable characters (min 3 required)")
        return cleaned


class QueryClarificationResponse(BaseModel):
    """Returned when a query requires disambiguation or exceeds archive capabilities."""

    status: Literal["clarification_required"] = "clarification_required"
    clarification_question: str = Field(..., description="Clarification prompt for user")
    assumptions: list[str] = Field(
        default_factory=list, description="Assumptions documented during parsing"
    )
    plan: QueryPlan | None = Field(default=None, description="Partial query plan")


class JobCreatedResponse(BaseModel):
    """Response returned upon successful async job registration (HTTP 202)."""

    status: Literal["accepted"] = "accepted"
    job_id: str = Field(..., description="Unique UUID identifying the analysis job")
    job_url: str = Field(..., description="API endpoint to poll job progress")
    state: Literal["queued", "running"] = "queued"
    plan: QueryPlan = Field(..., description="Interpreted analysis plan")


class JobStatusResponse(BaseModel):
    """Detailed job status and execution progress payload."""

    job_id: str
    status: Literal["queued", "running", "succeeded", "failed"]
    stage: str = Field(default="Registered", description="Current pipeline stage description")
    progress_percent: int = Field(default=0, ge=0, le=100)
    created_at: datetime
    started_at: datetime | None = None
    completed_at: datetime | None = None
    query: str
    plan: QueryPlan | None = None
    error: str | None = None
    stats: dict[str, Any] | None = None
    is_demo: bool = Field(
        default=False, description="True if result originates from cached benchmark run"
    )
    artifacts: dict[str, str] = Field(
        default_factory=dict, description="Available output download links"
    )


class LayerListResponse(BaseModel):
    """Available vector layers for a job."""

    job_id: str
    layers: list[str] = Field(
        ..., description="List of valid layer names, e.g. ['gained', 'lost', 'persistent']"
    )


class ExampleItem(BaseModel):
    """Pre-configured query example."""

    id: str
    title: str
    query: str
    description: str
    is_cached_demo: bool = False


class ExamplesResponse(BaseModel):
    """List of example queries."""

    examples: list[ExampleItem]


class HealthCheckResponse(BaseModel):
    """Health check payload."""

    status: str = "ok"
    version: str
    demo_mode: bool = False
    timestamp: datetime
